/**
 * 地理底稿（艺术化示意，非测绘）。数据由旧项目清洗导入：区域海拔、山脉、名山、江河、湖泊、长城。
 * 坐标一律为 [经度, 纬度]。
 */

export type GeoLine = readonly (readonly [number, number])[]

export type RegionKind = 'steppe' | 'gobi' | 'loess' | 'plateau' | 'desert' | 'plain' | 'karst' | 'redbasin'

export interface RegionDef {
  polygon: GeoLine
  /** 海拔（米），null 表示只改起伏 */
  elevation: number | null
  /** 边缘柔化半径（度） */
  blur: number
  /** 起伏幅度（米） */
  relief: number | null
  kind?: RegionKind
}

export interface RangeDef {
  line: GeoLine
  /** 高出周边（米） */
  height: number
  /** 半宽（度） */
  halfWidth: number
}

export interface PeakDef {
  lng: number
  lat: number
  height: number
  halfWidth: number
}

export interface RiverDef {
  id: string
  name: string
  line: GeoLine
  /** 源头与河口的半宽（方块）：干流宽、支流窄，按实际大小分级 */
  widthStart: number
  widthEnd: number
  /** 沿程实测水面海拔 [经度, 纬度, 米]：定水位，不靠宏观网格推算 */
  levels?: readonly (readonly [number, number, number])[]
}

export interface LakeDef {
  lng: number
  lat: number
  /** 椭圆半径（艺术化单位） */
  rx: number
  rz: number
  rotation: number
}

